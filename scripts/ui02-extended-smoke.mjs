import assert from "node:assert/strict";
import {createState,apply,validateState,upgradeState,makeHistory,dispatch,undo,redo,DETAIL_CONTROLS,MOTION_MODES,AMBIENCE_TYPES} from "../interaction-state.mjs";
import {UI02_EXTENDED,extendedBounds} from "../ui02-extended-layout.mjs";
const orig=createState("UI_02");
assert(validateState(orig));
assert.equal(orig.mode.MOTION,"PASS_BY");
assert.equal(orig.mode.AMBIENCE,"TRAFFIC");
assert.equal(orig.detail.speed,60);
assert.equal(orig.detail.ambienceLevel,-18);
assert.equal(DETAIL_CONTROLS.length,9);
assert.equal(MOTION_MODES.length,5);
assert.equal(AMBIENCE_TYPES.length,10);
const legacy=JSON.parse(JSON.stringify(orig));delete legacy.detail;delete legacy.mode;delete legacy.extraBypass;delete legacy.ambienceSeed;
legacy.params.motion=83;
const upgraded=upgradeState(legacy,"UI_02");
assert.equal(upgraded.params.motion,83);
assert.equal(upgraded.detail.speed,60);
assert(validateState(upgraded));
let h=makeHistory(orig);
h=dispatch(h,{type:"mode",group:"MOTION",value:"APPROACH"});
h=dispatch(h,{type:"detail",id:"speed",value:125});
h=dispatch(h,{type:"mode",group:"AMBIENCE",value:"RAIN"});
h=dispatch(h,{type:"auxBypass",group:"AMBIENCE"});
h=dispatch(h,{type:"newSeed"});
assert.equal(h.present.ambienceSeed,2);
assert(h.present.extraBypass.AMBIENCE);
h=undo(h);assert.equal(h.present.ambienceSeed,1);
h=redo(h);assert.equal(h.present.ambienceSeed,2);
assert.equal(apply(orig,{type:"detail",id:"speed",value:800}).detail.speed,300);
assert.throws(()=>apply(orig,{type:"mode",group:"MOTION",value:"INVALID"}));
assert.throws(()=>apply(orig,{type:"detail",id:"PRIVATE_ALGORITHM",value:50}));
for(const [name,b] of Object.entries(UI02_EXTENDED.panels)){
  const r=extendedBounds(name);
  assert(b.x>=0&&b.y>=0&&b.x+b.w<=UI02_EXTENDED.width&&b.y+b.h<=UI02_EXTENDED.height);
  assert(r.left>=0&&r.top>=0&&r.width>0&&r.height>0&&r.left+r.width<=100.0001);
}
const a=UI02_EXTENDED.panels.MOTION,b=UI02_EXTENDED.panels.AMBIENCE;
assert.equal(Math.max(0,Math.min(a.x+a.w,b.x+b.w)-Math.max(a.x,b.x)),0);
console.log("PASS: UI_02 Motion/Ambience state, legacy migration, history and confirmed nonoverlap");
